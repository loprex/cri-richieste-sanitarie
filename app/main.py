def sign(v):return hmac.new(SESSION_SECRET.encode(),v.encode(),hashlib.sha256).hexdigest()
def require_admin(req:Request):
    raw=req.cookies.get('cri_admin','')
    if '.' not in raw:raise HTTPException(401,'Accesso richiesto')
    v,s=raw.rsplit('.',1)
    if not hmac.compare_digest(sign(v),s):raise HTTPException(401,'Sessione non valida')
    try:expiry=int(v)
    except ValueError:raise HTTPException(401,'Sessione non valida')
    if expiry<int(now().timestamp()):raise HTTPException(401,'Sessione scaduta')
    if req.method not in ('GET','HEAD') and not hmac.compare_digest(req.headers.get('x-cri-csrf',''),sign('csrf:'+v)):
        raise HTTPException(403,'Protezione CSRF')
    return v

def get_token_record(token):
    if not re.fullmatch(r'[A-Za-z0-9_-]{35,128}',token):raise HTTPException(404,'Link non valido')
    with db() as c:r=fetchone(c,'SELECT * FROM requests WHERE token_hash=:hash',{'hash':digest(token)})
    if not r:raise HTTPException(404,'Link non trovato')
    if datetime.fromisoformat(r['expires_at'])<now():raise HTTPException(410,'Link scaduto')
    return r

