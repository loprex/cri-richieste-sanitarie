def password_hash(password:str)->str:
    salt=secrets.token_bytes(16)
    hashed=hashlib.pbkdf2_hmac('sha256',password.encode(),salt,600000)
    return 'pbkdf2_sha256$600000$'+salt.hex()+'$'+hashed.hex()
def verify_password(password:str,stored:str)->bool:
    try:
        kind,iterations,salt,hashed=stored.split('$')
        if kind!='pbkdf2_sha256' or not (100000<=int(iterations)<=1000000):return False
        candidate=hashlib.pbkdf2_hmac('sha256',password.encode(),bytes.fromhex(salt),int(iterations))
        return hmac.compare_digest(candidate,bytes.fromhex(hashed))
    except (ValueError,TypeError):return False
