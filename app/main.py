def sign(v):return hmac.new(SESSION_SECRET.encode(),v.encode(),hashlib.sha256).hexdigest()
def require_user(req:Request):
    raw=req.cookies.get('cri_admin','')
    if '.' not in raw:raise HTTPException(401,'Accesso richiesto')
    value,signature=raw.rsplit('.',1)
    if not hmac.compare_digest(sign(value),signature):raise HTTPException(401,'Sessione non valida')
    try:
        user_id,auth_version,expiry=value.split(':')
        if int(expiry)<int(now().timestamp()):raise HTTPException(401,'Sessione scaduta')
        user_id=int(user_id)
    except (ValueError,TypeError):raise HTTPException(401,'Sessione non valida')
    if req.method not in ('GET','HEAD') and not hmac.compare_digest(
          req.headers.get('x-cri-csrf',''),sign('csrf:'+value)):
        raise HTTPException(403,'Protezione CSRF')
    with db() as c:
        user=fetchone(c,'SELECT id,username,email,display_name,role,active,auto_locked_at,auth_version FROM app_users WHERE id=:id',{'id':user_id})
    if not user or not user['active'] or user['auto_locked_at'] or not hmac.compare_digest(user['auth_version'],auth_version):
        raise HTTPException(401,'Sessione revocata')
    return dict(user,csrf=sign('csrf:'+value))
